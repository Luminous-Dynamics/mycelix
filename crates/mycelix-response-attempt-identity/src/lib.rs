/// Prepare one exact attempt identity and its #298 admission subject.
///
/// `attempt_nonce` and `attempt_ref` are candidate identity only. A later native
/// durable store must own/generate or otherwise independently trust them and
/// persist the exact manifest before any effect-capable call.
pub fn prepare_response_attempt(
    current: &QualifiedResponseCurrentExecutor,
    safety: &QualifiedResponseEffectSafety,
    attempt_nonce: [u8; 32],
    attempt_ref: impl Into<String>,
    now_ms: u64,
) -> Result<PreparedResponseAttempt, ResponseAttemptIdentityError> {
    if now_ms == 0 {
        return Err(ResponseAttemptIdentityError::InvalidPreparationTime);
    }
    if attempt_nonce == [0u8; 32] {
        return Err(ResponseAttemptIdentityError::ZeroAttemptNonce);
    }
    let attempt_ref = attempt_ref.into();
    require_ref(&attempt_ref)?;

    if current.valid_until_ms() <= now_ms || safety.valid_until_ms() <= now_ms {
        return Err(ResponseAttemptIdentityError::UpstreamQualificationExpired);
    }
    if current.response_safety_qualification_digest() != safety.qualification_digest() {
        return Err(ResponseAttemptIdentityError::ResponseSafetyIdentityMismatch);
    }
    if !safety.all_declared_authority_subjects_satisfied() {
        return Err(ResponseAttemptIdentityError::PendingAuthoritySubjects);
    }

    require_exact_response_equality(current, safety)?;

    let effect_identity_digest = effect_identity(safety);
    let response_current_executor_digest = current.qualification_digest();
    let response_safety_digest = safety.qualification_digest();
    let attempt_identity_digest = attempt_identity(
        effect_identity_digest,
        response_current_executor_digest,
        response_safety_digest,
        &attempt_nonce,
        &attempt_ref,
    );

    // #298's subject binds the exact current response authority theorem plus a
    // separate attempt nonce/ref. The stable effect key remains a journal concern
    // and is also committed by our attempt identity.
    let coordinator_admission_subject = CoordinatorAdmissionSubject {
        protocol_version: STABILITY_PROTOCOL_VERSION.into(),
        subject_digest: current.qualification_digest().0,
        subject_profile: current.qualification_profile().into(),
        attempt_nonce,
        attempt_ref: attempt_ref.clone(),
    };
    coordinator_admission_subject
        .validate()
        .map_err(|error| ResponseAttemptIdentityError::CoordinatorSubject(error.to_string()))?;

    let max_attempt_lease_ms = safety.max_attempt_lease_ms();
    if max_attempt_lease_ms == 0 {
        return Err(ResponseAttemptIdentityError::ZeroAttemptLease);
    }
    let policy_horizon = now_ms
        .checked_add(max_attempt_lease_ms)
        .ok_or(ResponseAttemptIdentityError::AttemptLeaseOverflow)?;
    let valid_until_ms = current
        .valid_until_ms()
        .min(safety.valid_until_ms())
        .min(policy_horizon);
    if valid_until_ms <= now_ms {
        return Err(ResponseAttemptIdentityError::NoUsableAttemptWindow);
    }

    let evidence_digest = evidence_identity(
        attempt_identity_digest,
        current.evidence_digest(),
        safety.evidence_digest(),
        now_ms,
        valid_until_ms,
    );

    Ok(PreparedResponseAttempt {
        proposal_id: safety.proposal_id().into(),
        proposal_digest: safety.proposal_digest().into(),
        decision_id: safety.decision_id().into(),
        option_id: safety.option_id().into(),
        action_class: safety.action_class().into(),
        actions_digest: safety.actions_digest(),
        actions_digest_profile: safety.actions_digest_profile().into(),
        adapter_profile: safety.adapter_profile().into(),
        effect_identity_digest,
        response_current_executor_digest,
        response_safety_digest,
        attempt_nonce,
        attempt_ref,
        attempt_identity_digest,
        coordinator_admission_subject,
        automatic_effects_allowed: safety.automatic_effects_allowed(),
        max_attempt_lease_ms,
        evidence_digest,
        prepared_at_ms: now_ms,
        valid_until_ms,
    })
}

fn require_exact_response_equality(
    current: &QualifiedResponseCurrentExecutor,
    safety: &QualifiedResponseEffectSafety,
) -> Result<(), ResponseAttemptIdentityError> {
    if current.proposal_id() != safety.proposal_id()
        || current.proposal_digest() != safety.proposal_digest()
        || current.decision_id() != safety.decision_id()
        || current.option_id() != safety.option_id()
    {
        return Err(ResponseAttemptIdentityError::ResponseIdentityMismatch);
    }
    if current.action_class() != safety.action_class()
        || current.actions_digest() != safety.actions_digest()
        || current.actions_digest_profile() != safety.actions_digest_profile()
        || current.jurisdiction() != safety.jurisdiction()
    {
        return Err(ResponseAttemptIdentityError::ResponseActionMismatch);
    }
    if current.executor_authority_ref() != safety.executor_authority_ref() {
        return Err(ResponseAttemptIdentityError::ExecutorAuthorityMismatch);
    }
    Ok(())
}

/// Stable key for the exact selected effect. It intentionally excludes current
/// executor/safety generations and dynamic evidence horizons.
fn effect_identity(safety: &QualifiedResponseEffectSafety) -> Digest32 {
    let mut hasher = blake3::Hasher::new();
    hasher.update(DOMAIN_EFFECT);
    frame(&mut hasher, PROTOCOL_VERSION.as_bytes());
    frame(&mut hasher, EFFECT_IDENTITY_PROFILE.as_bytes());
    frame(&mut hasher, safety.proposal_id().as_bytes());
    frame(&mut hasher, safety.proposal_digest().as_bytes());
    frame(&mut hasher, safety.decision_id().as_bytes());
    frame(&mut hasher, safety.option_id().as_bytes());
    frame(&mut hasher, safety.action_class().as_bytes());
    frame(&mut hasher, &safety.actions_digest().0);
    frame(&mut hasher, safety.actions_digest_profile().as_bytes());
    frame(&mut hasher, safety.adapter_profile().as_bytes());
    Digest32(*hasher.finalize().as_bytes())
}

fn attempt_identity(
    effect_identity: Digest32,
    current_executor_identity: Digest32,
    safety_identity: Digest32,
    nonce: &[u8; 32],
    attempt_ref: &str,
) -> Digest32 {
    let mut hasher = blake3::Hasher::new();
    hasher.update(DOMAIN_ATTEMPT);
    frame(&mut hasher, PROTOCOL_VERSION.as_bytes());
    frame(&mut hasher, ATTEMPT_IDENTITY_PROFILE.as_bytes());
    frame(&mut hasher, &effect_identity.0);
    frame(&mut hasher, EFFECT_IDENTITY_PROFILE.as_bytes());
    frame(&mut hasher, &current_executor_identity.0);
    frame(&mut hasher, &safety_identity.0);
    frame(&mut hasher, nonce);
    frame(&mut hasher, attempt_ref.as_bytes());
    Digest32(*hasher.finalize().as_bytes())
}

fn evidence_identity(
    attempt_identity: Digest32,
    current_evidence: Digest32,
    safety_evidence: Digest32,
    prepared_at_ms: u64,
    valid_until_ms: u64,
) -> Digest32 {
    let mut hasher = blake3::Hasher::new();
    hasher.update(DOMAIN_EVIDENCE);
    frame(&mut hasher, EVIDENCE_PROFILE.as_bytes());
    frame(&mut hasher, &attempt_identity.0);
    frame(&mut hasher, &current_evidence.0);
    frame(&mut hasher, &safety_evidence.0);
    frame(&mut hasher, &prepared_at_ms.to_le_bytes());
    frame(&mut hasher, &valid_until_ms.to_le_bytes());
    Digest32(*hasher.finalize().as_bytes())
}

fn require_ref(value: &str) -> Result<(), ResponseAttemptIdentityError> {
    if value.trim().is_empty() || value.len() > MAX_REF_BYTES {
        Err(ResponseAttemptIdentityError::InvalidAttemptReference)
    } else {
        Ok(())
    }
}

fn frame(hasher: &mut blake3::Hasher, bytes: &[u8]) {
    hasher.update(&(bytes.len() as u64).to_le_bytes());
    hasher.update(bytes);
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ResponseAttemptIdentityError {
    InvalidPreparationTime,
    ZeroAttemptNonce,
    InvalidAttemptReference,
    UpstreamQualificationExpired,
    ResponseSafetyIdentityMismatch,
    PendingAuthoritySubjects,
    ResponseIdentityMismatch,
    ResponseActionMismatch,
    ExecutorAuthorityMismatch,
    CoordinatorSubject(String),
    ZeroAttemptLease,
    AttemptLeaseOverflow,
    NoUsableAttemptWindow,
}

impl fmt::Display for ResponseAttemptIdentityError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidPreparationTime => write!(f, "attempt preparation time must be non-zero"),
            Self::ZeroAttemptNonce => write!(f, "attempt nonce must not be zero"),
            Self::InvalidAttemptReference => write!(f, "invalid attempt reference"),
            Self::UpstreamQualificationExpired => write!(f, "upstream response qualification is not live"),
            Self::ResponseSafetyIdentityMismatch => write!(f, "current executor was bound to another response-safety identity"),
            Self::PendingAuthoritySubjects => write!(f, "response still has unresolved declared authority subjects"),
            Self::ResponseIdentityMismatch => write!(f, "response/current-executor identity fields differ"),
            Self::ResponseActionMismatch => write!(f, "response/current-executor action fields differ"),
            Self::ExecutorAuthorityMismatch => write!(f, "response/current-executor authority references differ"),
            Self::CoordinatorSubject(error) => write!(f, "invalid coordinator admission subject: {error}"),
            Self::ZeroAttemptLease => write!(f, "effect-safety policy permits no attempt lease"),
            Self::AttemptLeaseOverflow => write!(f, "attempt lease horizon overflowed"),
            Self::NoUsableAttemptWindow => write!(f, "no overlapping attempt evidence window remains"),
        }
    }
}

impl std::error::Error for ResponseAttemptIdentityError {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn effect_identity_source_excludes_authority_generations_and_time() {
        let source = include_str!("lib.rs");
        let body = source
            .split("fn effect_identity(", 2)
            .nth(1)
            .unwrap()
            .split("fn attempt_identity(", 2)
            .next()
            .unwrap();
        for forbidden in [
            "executor_authority_ref",
            "qualification_digest",
            "evidence_digest",
            "verified_at_ms",
            "valid_until_ms",
            "effect_safety_qualification_digest",
        ] {
            assert!(!body.contains(forbidden), "{forbidden}");
        }
        for required in [
            "proposal_digest()",
            "decision_id()",
            "option_id()",
            "actions_digest()",
            "adapter_profile()",
        ] {
            assert!(body.contains(required), "{required}");
        }
    }

    #[test]
    fn attempt_identity_does_bind_current_authority_and_nonce() {
        let source = include_str!("lib.rs");
        let body = source
            .split("fn attempt_identity(", 2)
            .nth(1)
            .unwrap()
            .split("fn evidence_identity(", 2)
            .next()
            .unwrap();
        assert!(body.contains("current_executor_identity"));
        assert!(body.contains("safety_identity"));
        assert!(body.contains("nonce"));
        assert!(body.contains("attempt_ref"));
    }
}
