//! Pure exact attempt identity for one response effect.
//!
//! This crate intentionally separates three identities:
//!
//! 1. **effect identity** — what physical/logical effect is being attempted;
//! 2. **authority qualification identity** — which exact current executor and
//!    safety qualification prepared it; and
//! 3. **attempt identity** — one nonce/reference for one try at that effect.
//!
//! Effect identity deliberately excludes current authority generations and
//! dynamic verification times so an authority refresh cannot create a new effect
//! namespace and accidentally permit duplicate physical action.
//!
//! This is not durable reservation. The caller-supplied attempt nonce/reference
//! are only candidate attempt identity until a later trusted journal owns and
//! persists them before any effect.

use mycelix_authority_coordinator_stability_fence::{
    CoordinatorAdmissionSubject, PROTOCOL_VERSION as STABILITY_PROTOCOL_VERSION,
};
use mycelix_institutional_core::Digest32;
use mycelix_response_current_executor::QualifiedResponseCurrentExecutor;
use mycelix_response_effect_safety::QualifiedResponseEffectSafety;
use serde::Serialize;
use std::fmt;

pub const PROTOCOL_VERSION: &str = "mycelix-response-attempt-identity-v0.1";
pub const EFFECT_IDENTITY_PROFILE: &str =
    "mycelix-response-effect-identity-v1-blake3-framed";
pub const ATTEMPT_IDENTITY_PROFILE: &str =
    "mycelix-response-attempt-identity-v1-blake3-framed";
pub const EVIDENCE_PROFILE: &str =
    "mycelix-response-attempt-evidence-v1-blake3-framed";

const DOMAIN_EFFECT: &[u8] = b"mycelix/response/effect-identity/v1";
const DOMAIN_ATTEMPT: &[u8] = b"mycelix/response/attempt-identity/v1";
const DOMAIN_EVIDENCE: &[u8] = b"mycelix/response/attempt-evidence/v1";
const MAX_REF_BYTES: usize = 2048;

/// Non-deserializable prepared attempt identity.
///
/// It is suitable as the exact subject for #298 coordinator stability fencing,
/// but does not prove its nonce/reference were generated by a trusted runtime or
/// written durably.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct PreparedResponseAttempt {
    proposal_id: String,
    proposal_digest: String,
    decision_id: String,
    option_id: String,
    action_class: String,
    actions_digest: Digest32,
    actions_digest_profile: String,
    adapter_profile: String,
    effect_identity_digest: Digest32,
    response_current_executor_digest: Digest32,
    response_safety_digest: Digest32,
    attempt_nonce: [u8; 32],
    attempt_ref: String,
    attempt_identity_digest: Digest32,
    coordinator_admission_subject: CoordinatorAdmissionSubject,
    automatic_effects_allowed: bool,
    max_attempt_lease_ms: u64,
    evidence_digest: Digest32,
    prepared_at_ms: u64,
    valid_until_ms: u64,
}

