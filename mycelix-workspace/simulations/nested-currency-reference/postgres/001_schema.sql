-- NCF PostgreSQL shared-coordinator reference schema.
-- This migration is a PostgreSQL target, not a SQLite-compatible schema.
BEGIN;
CREATE SCHEMA IF NOT EXISTS ncf;

CREATE TABLE IF NOT EXISTS ncf.instrument_identity (
    instrument_id          text PRIMARY KEY,
    issuer_community_id    text NOT NULL,
    instrument_family      text NOT NULL,
    denomination_code      text NOT NULL,
    unit_scale             integer NOT NULL CHECK (unit_scale >= 0 AND unit_scale <= 18),
    transferable           boolean NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (length(btrim(instrument_id)) > 0),
    CHECK (length(btrim(issuer_community_id)) > 0),
    CHECK (length(btrim(denomination_code)) > 0)
);

CREATE TABLE IF NOT EXISTS ncf.instrument_profile_revision (
    instrument_id      text NOT NULL REFERENCES ncf.instrument_identity(instrument_id),
    profile_revision   integer NOT NULL CHECK (profile_revision > 0),
    profile_digest     bytea NOT NULL CHECK (octet_length(profile_digest) = 32),
    policy             jsonb NOT NULL,
    published_at       timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (instrument_id, profile_revision)
);

CREATE TABLE IF NOT EXISTS ncf.clearing_agreement (
    agreement_id       uuid PRIMARY KEY,
    community_a        text NOT NULL,
    community_b        text NOT NULL,
    instrument_id      text NOT NULL,
    profile_revision   integer NOT NULL,
    state              text NOT NULL DEFAULT 'active'
                       CHECK (state IN ('active', 'paused', 'closed')),
    created_at         timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY (instrument_id, profile_revision)
      REFERENCES ncf.instrument_profile_revision(instrument_id, profile_revision),
    CHECK (community_a <> community_b),
    CHECK (length(btrim(community_a)) > 0 AND length(btrim(community_b)) > 0)
);

CREATE TABLE IF NOT EXISTS ncf.agreement_direction_cap (
    agreement_id       uuid NOT NULL REFERENCES ncf.clearing_agreement(agreement_id),
    direction          text NOT NULL CHECK (direction IN ('a_to_b', 'b_to_a')),
    community_id       text NOT NULL,
    instrument_id      text NOT NULL REFERENCES ncf.instrument_identity(instrument_id),
    cap_units          numeric(78,0) NOT NULL CHECK (cap_units >= 0),
    allocated_units    numeric(78,0) NOT NULL DEFAULT 0 CHECK (allocated_units >= 0),
    outstanding_units  numeric(78,0) NOT NULL DEFAULT 0 CHECK (outstanding_units >= 0),
    PRIMARY KEY (agreement_id, direction),
    CHECK (allocated_units <= cap_units),
    CHECK (outstanding_units <= allocated_units)
);

CREATE TABLE IF NOT EXISTS ncf.community_instrument_cap (
    community_id       text NOT NULL,
    instrument_id      text NOT NULL REFERENCES ncf.instrument_identity(instrument_id),
    cap_units          numeric(78,0) NOT NULL CHECK (cap_units >= 0),
    allocated_units    numeric(78,0) NOT NULL DEFAULT 0 CHECK (allocated_units >= 0),
    outstanding_units  numeric(78,0) NOT NULL DEFAULT 0 CHECK (outstanding_units >= 0),
    PRIMARY KEY (community_id, instrument_id),
    CHECK (allocated_units <= cap_units),
    CHECK (outstanding_units <= allocated_units)
);

-- Reservations are non-overlapping rights allocated before a shard may operate
-- offline. A capacity slice is not a lease and is not reclaimed just because a
-- peer is unreachable. All online coordinator writes use one PostgreSQL database.
CREATE TABLE IF NOT EXISTS ncf.reservation_slice (
    reservation_id     uuid PRIMARY KEY,
    agreement_id       uuid NOT NULL REFERENCES ncf.clearing_agreement(agreement_id),
    community_id       text NOT NULL,
    instrument_id      text NOT NULL REFERENCES ncf.instrument_identity(instrument_id),
    direction          text NOT NULL CHECK (direction IN ('a_to_b', 'b_to_a')),
    shard_id           text NOT NULL,
    epoch              bigint NOT NULL CHECK (epoch >= 0),
    reserved_units     numeric(78,0) NOT NULL CHECK (reserved_units > 0),
    used_units         numeric(78,0) NOT NULL DEFAULT 0 CHECK (used_units >= 0),
    manifest_digest    bytea NOT NULL CHECK (octet_length(manifest_digest) = 32),
    state              text NOT NULL DEFAULT 'active'
                       CHECK (state IN ('active', 'paused', 'retired')),
    created_at         timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (agreement_id, community_id, direction, shard_id, epoch),
    FOREIGN KEY (agreement_id, direction)
      REFERENCES ncf.agreement_direction_cap(agreement_id, direction),
    CHECK (length(btrim(shard_id)) > 0),
    CHECK (used_units <= reserved_units)
);

CREATE TABLE IF NOT EXISTS ncf.obligation (
    obligation_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_work_digest  bytea NOT NULL UNIQUE CHECK (octet_length(canonical_work_digest) = 32),
    principal_id           text NOT NULL,
    community_id           text NOT NULL,
    instrument_id          text NOT NULL,
    profile_revision       integer NOT NULL,
    amount_units           numeric(78,0) NOT NULL CHECK (amount_units > 0),
    agreement_id           uuid NOT NULL REFERENCES ncf.clearing_agreement(agreement_id),
    direction              text NOT NULL CHECK (direction IN ('a_to_b', 'b_to_a')),
    reservation_id         uuid NOT NULL REFERENCES ncf.reservation_slice(reservation_id),
    shard_id               text NOT NULL,
    epoch                  bigint NOT NULL CHECK (epoch >= 0),
    state                  text NOT NULL DEFAULT 'outstanding'
                           CHECK (state IN ('outstanding', 'settled', 'disputed', 'reversed')),
    receipt_json           jsonb NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
    settled_at             timestamptz,
    FOREIGN KEY (instrument_id, profile_revision)
      REFERENCES ncf.instrument_profile_revision(instrument_id, profile_revision),
    FOREIGN KEY (agreement_id, direction)
      REFERENCES ncf.agreement_direction_cap(agreement_id, direction),
    CHECK (length(btrim(principal_id)) > 0 AND length(btrim(community_id)) > 0),
    CHECK (length(btrim(shard_id)) > 0),
    CHECK ((state = 'outstanding' AND settled_at IS NULL)
        OR (state <> 'outstanding' AND settled_at IS NOT NULL))
);

-- Each request key binds immutable payload and verifier evidence. An alias may
-- point at an already accepted canonical obligation, but does not debit twice.
CREATE TABLE IF NOT EXISTS ncf.request_binding (
    request_id                uuid PRIMARY KEY,
    payload_digest            bytea NOT NULL CHECK (octet_length(payload_digest) = 32),
    principal_id              text NOT NULL,
    community_id              text NOT NULL,
    instrument_id             text NOT NULL,
    profile_revision          integer NOT NULL,
    amount_units              numeric(78,0) NOT NULL CHECK (amount_units > 0),
    canonical_work_digest     bytea NOT NULL CHECK (octet_length(canonical_work_digest) = 32),
    agreement_id              uuid NOT NULL REFERENCES ncf.clearing_agreement(agreement_id),
    direction                 text NOT NULL CHECK (direction IN ('a_to_b', 'b_to_a')),
    reservation_id            uuid NOT NULL REFERENCES ncf.reservation_slice(reservation_id),
    shard_id                  text NOT NULL,
    epoch                     bigint NOT NULL CHECK (epoch >= 0),
    verifier_version          text NOT NULL,
    verifier_receipt_digest   bytea NOT NULL CHECK (octet_length(verifier_receipt_digest) = 32),
    obligation_id             bigint NOT NULL REFERENCES ncf.obligation(obligation_id),
    decision                  text NOT NULL CHECK (decision IN ('accepted', 'replay')),
    receipt_json              jsonb NOT NULL,
    created_at                timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY (instrument_id, profile_revision)
      REFERENCES ncf.instrument_profile_revision(instrument_id, profile_revision),
    CHECK (length(btrim(verifier_version)) > 0 AND length(btrim(shard_id)) > 0)
);

CREATE TABLE IF NOT EXISTS ncf.settlement_receipt (
    settlement_id          uuid PRIMARY KEY,
    obligation_id           bigint NOT NULL UNIQUE REFERENCES ncf.obligation(obligation_id),
    settlement_digest       bytea NOT NULL CHECK (octet_length(settlement_digest) = 32),
    receipt_json             jsonb NOT NULL,
    created_at               timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Transactional outbox: the economic row and its publish intent commit together.
-- Outbox status means dispatch state, not Holochain validation or settlement finality.
CREATE TABLE IF NOT EXISTS ncf.holochain_outbox (
    outbox_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id       bigint NOT NULL REFERENCES ncf.obligation(obligation_id),
    event_type          text NOT NULL CHECK (event_type IN ('obligation_accepted', 'obligation_settled')),
    payload_json        jsonb NOT NULL,
    payload_sha256      bytea NOT NULL CHECK (octet_length(payload_sha256) = 32),
    state               text NOT NULL DEFAULT 'pending'
                        CHECK (state IN ('pending', 'leased', 'published', 'retry', 'dead')),
    attempt_count       integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at     timestamptz NOT NULL DEFAULT clock_timestamp(),
    lease_owner         text,
    lease_until         timestamptz,
    holochain_action_hash text,
    last_error          text,
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    published_at        timestamptz,
    UNIQUE (obligation_id, event_type)
);

CREATE INDEX IF NOT EXISTS holochain_outbox_due_idx
    ON ncf.holochain_outbox(state, next_attempt_at, outbox_id);

-- This table is an observed projection of Holochain actions/receipts, not a
-- claim that PostgreSQL can manufacture or certify DHT validation.
CREATE TABLE IF NOT EXISTS ncf.holochain_action_observation (
    dna_hash                 text NOT NULL,
    action_hash              text NOT NULL,
    outbox_id                bigint REFERENCES ncf.holochain_outbox(outbox_id),
    author_agent             text NOT NULL,
    entry_hash               text,
    validation_receipt_count integer NOT NULL DEFAULT 0 CHECK (validation_receipt_count >= 0),
    observation_state         text NOT NULL
                              CHECK (observation_state IN ('authored', 'dispatched', 'receipts_observed', 'invalidated', 'unresolved')),
    observed_at               timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (dna_hash, action_hash)
);

CREATE OR REPLACE FUNCTION ncf.reject_immutable_identity_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'NCF identity/profile rows are append-only: % on % is forbidden',
        TG_OP, TG_TABLE_NAME USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS instrument_identity_immutable ON ncf.instrument_identity;
CREATE TRIGGER instrument_identity_immutable
BEFORE UPDATE OR DELETE ON ncf.instrument_identity
FOR EACH ROW EXECUTE FUNCTION ncf.reject_immutable_identity_mutation();

DROP TRIGGER IF EXISTS instrument_profile_revision_immutable ON ncf.instrument_profile_revision;
CREATE TRIGGER instrument_profile_revision_immutable
BEFORE UPDATE OR DELETE ON ncf.instrument_profile_revision
FOR EACH ROW EXECUTE FUNCTION ncf.reject_immutable_identity_mutation();

-- Service-role separation. These are NOLOGIN capability roles; deployment grants
-- authenticated service identities membership out-of-band.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'ncf_app') THEN
    CREATE ROLE ncf_app NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'ncf_dispatcher') THEN
    CREATE ROLE ncf_dispatcher NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'ncf_observer') THEN
    CREATE ROLE ncf_observer NOLOGIN;
  END IF;
END;
$$;

REVOKE ALL ON ALL TABLES IN SCHEMA ncf FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA ncf FROM PUBLIC;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA ncf FROM PUBLIC;
GRANT USAGE ON SCHEMA ncf TO ncf_app, ncf_dispatcher, ncf_observer;
GRANT SELECT ON ALL TABLES IN SCHEMA ncf TO ncf_app;

COMMIT;